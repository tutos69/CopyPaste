import AppKit
import CryptoKit

struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image }

    var id = UUID()
    var kind: Kind
    var text: String?
    var imageFile: String?
    var hash: String
    var date: Date
    var pinned = false
}

/// Watches the general pasteboard and keeps a persistent history (like Windows + V).
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []

    /// Maximum number of unpinned items kept.
    let maxItems = 50

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private let imagesDir: URL
    private let historyURL: URL
    private var imageCache: [String: NSImage] = [:]

    /// Password managers mark secrets with these types; never record them.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init() {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("CopyPaste", isDirectory: true)
        imagesDir = base.appendingPathComponent("images", isDirectory: true)
        historyURL = base.appendingPathComponent("history.json")
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        lastChangeCount = pasteboard.changeCount
        load()
    }

    func start() {
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    // MARK: - Capture

    private func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = pasteboard.types ?? []
        if types.contains(where: { ignoredTypes.contains($0.rawValue) }) { return }

        let string = pasteboard.string(forType: .string)
        let image = imageData()
        let hasText = !(string?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ?? true)

        // "Copy Image" in browsers also puts the image URL as text; prefer the image then.
        let textIsJustURL = string.map { !$0.contains(" ") && URL(string: $0)?.scheme?.hasPrefix("http") == true } ?? false

        if let image, !hasText || textIsJustURL {
            insert(kind: .image, text: nil, imageData: image)
        } else if hasText, let string {
            insert(kind: .text, text: string, imageData: nil)
        }
    }

    private func imageData() -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        if let tiff = pasteboard.data(forType: .tiff),
           let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            return png
        }
        return nil
    }

    private func insert(kind: ClipItem.Kind, text: String?, imageData: Data?) {
        let payload = imageData ?? Data((text ?? "").utf8)
        let hash = kind.rawValue + ":" + SHA256.hash(data: payload).map { String(format: "%02x", $0) }.joined()

        if let index = items.firstIndex(where: { $0.hash == hash }) {
            var existing = items.remove(at: index)
            existing.date = Date()
            items.insert(existing, at: 0)
            save()
            return
        }

        var item = ClipItem(kind: kind, text: text, hash: hash, date: Date())
        if let imageData {
            let name = item.id.uuidString + ".png"
            try? imageData.write(to: imagesDir.appendingPathComponent(name))
            item.imageFile = name
        }
        items.insert(item, at: 0)
        trim()
        save()
    }

    private func trim() {
        while items.filter({ !$0.pinned }).count > maxItems,
              let last = items.lastIndex(where: { !$0.pinned }) {
            deleteFiles(of: items.remove(at: last))
        }
    }

    // MARK: - Actions

    func copyToPasteboard(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            guard let file = item.imageFile,
                  let data = try? Data(contentsOf: imagesDir.appendingPathComponent(file)) else { return }
            pasteboard.setData(data, forType: .png)
            if let tiff = NSImage(data: data)?.tiffRepresentation {
                pasteboard.setData(tiff, forType: .tiff)
            }
        }
        lastChangeCount = pasteboard.changeCount

        if let index = items.firstIndex(of: item) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        save()
    }

    func remove(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        deleteFiles(of: items.remove(at: index))
        save()
    }

    /// Like Windows: "Clear all" keeps pinned items.
    func clearUnpinned() {
        items.filter { !$0.pinned }.forEach(deleteFiles)
        items.removeAll { !$0.pinned }
        save()
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let file = item.imageFile else { return nil }
        if let cached = imageCache[file] { return cached }
        let image = NSImage(contentsOf: imagesDir.appendingPathComponent(file))
        imageCache[file] = image
        return image
    }

    // MARK: - Persistence

    private func deleteFiles(of item: ClipItem) {
        guard let file = item.imageFile else { return }
        imageCache[file] = nil
        try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(file))
    }

    private func load() {
        guard let data = try? Data(contentsOf: historyURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: historyURL, options: .atomic)
    }
}
